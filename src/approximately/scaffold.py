from approximately import Recorder, attribute


def test_mutating_calls_are_verified():
    """FM-3.2 guard: every mutating call must be followed by a verification."""
    from approximately import Recorder

    rec = Recorder("guard run", save=False)
    # drive your agent here; assert the convention directly:
    steps = rec.trace.steps
    mutating = [s for s in steps if s.kind == "tool_call"
                and s.meta.get("mutating")]
    for i, step in enumerate(mutating):
        later = steps[step.index + 1:]
        assert any(s.kind == "tool_call" and s.tool and
                   any(m in s.tool.lower() for m in ("verify", "check", "get_"))
                   for s in later), f"unverified mutating call: {{step.tool}}"


def test_no_repeated_tool_calls():
    """FM-1.3 guard: identical (tool, args) must not be called twice."""
    rec = Recorder("guard run", save=False)
    seen, repeats = set(), []
    for step in rec.trace.steps:
        if step.kind != "tool_call" or step.error:
            continue
        fp = step.fingerprint()
        if fp in seen:
            repeats.append(step.short())
        seen.add(fp)
    assert not repeats, f"repeated tool calls: {{repeats}}"
